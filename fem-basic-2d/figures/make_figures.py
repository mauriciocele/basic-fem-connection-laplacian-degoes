# ------------------------------------------------------------------------------------------------ vectors
def add(a, b): return tuple(x + y for x, y in zip(a, b))
def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def mul(a, s): return tuple(x * s for x in a)
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def norm(a): return math.sqrt(dot(a, a))
def unit(a): return mul(a, 1.0 / norm(a))
def lerp(a, b, t): return add(a, mul(sub(b, a), t))

def rotate(v, axis, angle):
    """Rodrigues rotation of v about the unit axis by angle."""
    k = unit(axis)
    c, s = math.cos(angle), math.sin(angle)
    return add(add(mul(v, c), mul(cross(k, v), s)), mul(k, dot(k, v) * (1 - c)))

def rotor_between(a, c):
    """The smallest rotation taking the unit vector a to the unit vector c, as a function."""
    axis = cross(a, c)
    if norm(axis) < 1e-12:
        return lambda v: v
    angle = math.atan2(norm(axis), dot(a, c))
    return lambda v: rotate(v, axis, angle)

def project_tangent(v, n): return sub(v, mul(n, dot(v, n)))

# ------------------------------------------------------------------------------------------------ camera
class Camera:
    def __init__(self, elev=25, azim=-60, scale=1.0):
        e, a = math.radians(elev), math.radians(azim)
        # view direction from the eye towards the origin; screen axes right and up
        self.right = (-math.sin(a), math.cos(a), 0.0)
        self.up = (-math.sin(e) * math.cos(a), -math.sin(e) * math.sin(a), math.cos(e))
        self.toward = (math.cos(e) * math.cos(a), math.cos(e) * math.sin(a), math.sin(e))
        self.scale = scale * 1.6

    def p(self, x):
        return (self.scale * dot(x, self.right), self.scale * dot(x, self.up))

    def depth(self, x):
        return dot(x, self.toward)

def fmt(pt): return '(%.4f,%.4f)' % pt

class Figure:
    def __init__(self, cam):
        self.cam = cam
        self.items = []   # (depth, code)

    def raw(self, code, depth=0.0): self.items.append((depth, code))

    def poly(self, pts, style, depth=None):
        d = depth if depth is not None else sum(self.cam.depth(q) for q in pts) / len(pts)
        self.items.append((d, '\\filldraw[%s] %s -- cycle;' % (style, ' -- '.join(fmt(self.cam.p(q)) for q in pts))))

    def line(self, pts, style, depth=None):
        d = depth if depth is not None else sum(self.cam.depth(q) for q in pts) / len(pts) + 1e-3
        self.items.append((d, '\\draw[%s] %s;' % (style, ' -- '.join(fmt(self.cam.p(q)) for q in pts))))

    def arrow(self, a, b, style, label=None, pos='right', depth=None):
        d = depth if depth is not None else max(self.cam.depth(a), self.cam.depth(b)) + 0.05
        code = '\\draw[-{Stealth[length=2.2mm]}, %s] %s -- %s' % (style, fmt(self.cam.p(a)), fmt(self.cam.p(b)))
        code += (' node[%s] {%s};' % (pos, label)) if label else ';'
        self.items.append((d, code))

    def dot_at(self, a, style='fill=black', r='1.2pt', label=None, pos='below', depth=None):
        d = depth if depth is not None else self.cam.depth(a) + 0.1
        code = '\\fill[%s] %s circle (%s)' % (style, fmt(self.cam.p(a)), r)
        code += (' node[%s] {%s};' % (pos, label)) if label else ';'
        self.items.append((d, code))

    def text(self, a, label, pos='', depth=10.0):
        self.items.append((depth, '\\node[%s] at %s {%s};' % (pos, fmt(self.cam.p(a)), label)))

    def write(self, name, options=''):
        body = '\n'.join(code for d, code in sorted(self.items, key=lambda t: t[0]))
        with open(os.path.join(HERE, name + '.tex'), 'w') as f:
            f.write('%% generated by make_figures.py\n\\begin{tikzpicture}[%s]\n%s\n\\end{tikzpicture}\n' % (options, body))

def plane_patch(c, n, t, size):
    b = cross(n, t)
    return [add(add(c, mul(t, sx * size)), mul(b, sy * size)) for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]

