def mesh_one_ring():
    """A vertex with six neighbors on a bumpy cone."""
    c = (0.0, 0.0, 0.35)
    ring = []
    for k in range(6):
        a = 2 * math.pi * k / 6 + 0.2
        z = 0.08 * math.cos(2 * a) + 0.03 * k
        ring.append((math.cos(a), math.sin(a), z))
    return c, ring

def face_normal(a, b, c): return unit(cross(sub(b, a), sub(c, a)))

def fig_one_ring():
    cam = Camera(28, -70, 2.0)
    F = Figure(cam)
    c, ring = mesh_one_ring()
    nsum = (0, 0, 0)
    for k in range(6):
        a, b = ring[k], ring[(k + 1) % 6]
        F.poly([c, a, b], 'draw=gray!70, fill=gray!12, line width=0.4pt')
        nf = face_normal(c, a, b)
        area = 0.5 * norm(cross(sub(a, c), sub(b, c)))
        nsum = add(nsum, mul(nf, 2 * area))
        g = mul(add(add(c, a), b), 1 / 3)
        F.arrow(g, add(g, mul(nf, 0.35)), 'gray!60!black, thin', depth=cam.depth(g) + 0.3)
    ni = unit(nsum)
    F.arrow(c, add(c, mul(ni, 0.75)), 'very thick, red!70!black', '$n_i$', 'above', depth=9)
    e = sub(ring[0], c)
    ti = unit(project_tangent(e, ni))
    F.poly(plane_patch(c, ni, ti, 0.45), 'draw=blue!60, fill=blue!10, fill opacity=0.7', depth=8)
    F.line([c, ring[0]], 'thick, orange!80!black', depth=8.5)
    F.arrow(c, add(c, mul(ti, 0.5)), 'thick, blue!70!black', '$t_i$', 'below', depth=9)
    F.arrow(c, add(c, mul(cross(ni, ti), 0.5)), 'thick, blue!70!black', '$b_i$', 'right', depth=9)
    F.dot_at(c, label='$x_i$', pos='left', depth=9.5)
    F.dot_at(ring[0], label='$x_j$', pos='below', depth=9.5)
    F.write('fig_one_ring')

def fig_rotor_transport():
    cam = Camera(20, -35, 2.6)
    F = Figure(cam)
    ni = unit((0.0, -0.25, 1.0))
    nf = unit((0.35, 0.45, 1.0))
    o = (0, 0, 0)
    ti = unit(project_tangent((1, 0.2, 0), ni))
    tf = unit(project_tangent((0.6, -0.8, 0), nf))
    F.poly(plane_patch(o, ni, ti, 0.75), 'draw=blue!60, fill=blue!10, fill opacity=0.6', depth=0)
    F.poly(plane_patch(o, nf, tf, 0.75), 'draw=orange!70, fill=orange!12, fill opacity=0.6', depth=0.1)
    F.arrow(o, mul(ni, 0.85), 'thick, blue!70!black', '$n_i$', 'above left', depth=5)
    F.arrow(o, mul(nf, 0.85), 'thick, orange!80!black', '$n_f$', 'above right', depth=5)
    axis = unit(cross(ni, nf))
    F.line([mul(axis, -0.95), mul(axis, 0.95)], 'dashed, gray', depth=4)
    F.text(mul(axis, 1.05), '$n_i \\times n_f$', 'gray!70!black')
    Q = rotor_between(ni, nf)
    qti = Q(ti)
    F.arrow(o, mul(ti, 0.62), 'thick, blue!70!black', '$t_i$', 'below', depth=5)
    F.arrow(o, mul(qti, 0.62), 'very thick, green!50!black', '$Q t_i \\widetilde Q$', 'below right', depth=5.2)
    F.arrow(o, mul(tf, 0.62), 'thick, orange!80!black', '$t_f$', 'left', depth=5)
    # the angle rho from t_f to Q t_i ~Q, in the face plane
    rho = math.atan2(dot(cross(tf, qti), nf), dot(tf, qti))
    pts = [mul(rotate(tf, nf, rho * s / 20), 0.3) for s in range(21)]
    F.line(pts, '->, green!50!black', depth=5.1)
    F.text(mul(rotate(tf, nf, rho / 2), 0.4), '$\\rho_i^f$', 'green!40!black')
    F.text(add(plane_patch(o, ni, ti, 0.75)[1], (0, 0, -0.05)), 'vertex plane', 'blue!60!black, below')
    F.text(plane_patch(o, nf, tf, 0.75)[2], 'face plane', 'orange!70!black, above')
    F.dot_at(o, depth=6)
    F.write('fig_rotor_transport')

def fig_unfold():
    cam = Camera(18, -110, 2.0)
    F = Figure(cam)
    p, q = (0, -0.9, 0), (0, 0.9, 0)          # the shared edge, along y
    a = (-1.1, 0.0, 0.0)                       # face f in the plane z = 0
    fold = math.radians(55)
    b = (1.1 * math.cos(fold), 0.0, 1.1 * math.sin(fold))   # face g, folded up about the edge
    bflat = (1.1, 0.0, 0.0)                    # face g unfolded into the plane of f
    nf = (0.0, 0.0, 1.0)
    ng = unit(cross(sub(q, p), sub(b, p)))
    if dot(ng, (-1, 0, 1)) < 0: ng = mul(ng, -1)
    F.poly([p, q, a], 'draw=blue!60, fill=blue!15', depth=0)
    F.poly([p, q, bflat], 'draw=orange!60, dashed, fill=orange!6', depth=-0.5)
    F.poly([p, q, b], 'draw=orange!70!black, fill=orange!25, fill opacity=0.9', depth=0.5)
    F.line([p, q], 'line width=1.4pt', depth=3)
    F.text(q, 'shared edge', 'right')
    o = (-0.45, -0.15, 0.0)
    v = (0.32, 0.38, 0.0)
    F.arrow(o, add(o, v), 'line width=1.3pt, green!50!black', '$v$', 'left', depth=4)
    R = rotor_between(nf, ng)
    o2 = (0.5 * math.cos(fold), 0.05, 0.5 * math.sin(fold))
    F.arrow(o2, add(o2, R(v)), 'line width=1.3pt, green!50!black', '$Q v \\widetilde Q$', 'right', depth=4)
    o3 = (0.5, 0.05, 0.0)
    F.arrow(o3, add(o3, v), 'green!50!black, dashed', depth=3.5)
    F.arrow((-0.7, 0.4, 0), (-0.7, 0.4, 0.45), 'thick, blue!70!black', '$n_f$', 'left', depth=4)
    cg = mul(add(add(p, q), b), 1 / 3)
    F.arrow(cg, add(cg, mul(ng, 0.45)), 'thick, orange!80!black', '$n_g$', 'above', depth=4)
    F.text(a, 'face $f$', 'left, blue!60!black')
    F.text(b, 'face $g$', 'above, orange!60!black')
    F.text(bflat, 'unfolded', 'below right, orange!60!black')
    F.write('fig_unfold')

