"""
Generates the 3D figures of fembasic2d.tex as TikZ code (one .tex file per figure, in this directory).

The geometry is computed here exactly (normals, rotations, unfolding) and projected orthographically, so that
every arrow in a figure is the true vector. Plain Python, no dependencies. Run from this directory:
    python3 make_figures.py ../data
where ../data holds the CSV files written by src/ga_fem.
"""
import csv
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
