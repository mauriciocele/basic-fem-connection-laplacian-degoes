def read_csv(name):
    with open(os.path.join(DATA, name)) as f:
        return [dict((k, float(v)) for k, v in row.items()) for row in csv.DictReader(f)]

def fig_sphere_result():
    rows = read_csv('sphere_vectors.csv')
    cam = Camera(35, -60, 2.0)
    F = Figure(cam)
    F.raw('\\fill[gray!8] (0,0) circle (%.3f);' % (cam.scale,), -100)
    F.raw('\\draw[gray!50] (0,0) circle (%.3f);' % (cam.scale,), -100)
    for r in rows:
        x = (r['x'], r['y'], r['z'])
        if dot(x, cam.toward) < 0.15:
            continue
        u = (r['ux'], r['uy'], r['uz'])
        e = (r['ex'], r['ey'], r['ez'])
        if r['distance'] > 2.36:
            continue
        # thin out
        if (abs(hash((round(x[0], 3), round(x[1], 3)))) % 3) != 0:
            continue
        F.arrow(x, add(x, mul(e, 0.09)), '-{Stealth[length=1.6mm]}, gray!55, line width=1.6pt', depth=1)
        F.arrow(x, add(x, mul(u, 0.09)), '-{Stealth[length=1.2mm]}, red!70!black, line width=0.5pt', depth=2)
    s0 = max(rows, key=lambda r: r['z'])
    F.dot_at((s0['x'], s0['y'], s0['z']), 'fill=blue!70!black', '2pt', 'source', 'above', depth=50)
    F.write('fig_sphere_result')

def fig_cactus_result():
    faces = read_csv('cactus_faces.csv')
    vecs = read_csv('cactus_vectors.csv')
    cam = Camera(12, 8, 1.9)
    F = Figure(cam)
    light = unit((0.3, -0.6, 0.8))
    tris = [((faces[k]['x'], faces[k]['y'], faces[k]['z']), (faces[k + 1]['x'], faces[k + 1]['y'], faces[k + 1]['z']),
             (faces[k + 2]['x'], faces[k + 2]['y'], faces[k + 2]['z'])) for k in range(0, len(faces), 3)]
    view = cam.toward
    for t in tris:
        n = face_normal(*t)
        if dot(n, view) < 0:     # back face
            continue
        shade = int(60 + 35 * max(0.0, dot(n, light)))
        F.poly(list(t), 'draw=gray!%d, fill=gray!%d, line width=0.1pt' % (shade - 15, 100 - shade))
    for r in vecs:
        x = (r['x'], r['y'], r['z'])
        u = (r['ux'], r['uy'], r['uz'])
        if dot((r['x'], r['y'], r['z']), cam.toward) < -0.02:
            continue
        F.arrow(x, add(x, mul(u, 0.05)), '-{Stealth[length=1.2mm]}, red!75!black, line width=0.45pt', depth=cam.depth(x) + 0.02)
    F.write('fig_cactus_result')

