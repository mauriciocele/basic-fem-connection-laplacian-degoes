def fig_rolling():
    cam = Camera(20, -50, 1.9)
    F = Figure(cam)
    # wireframe sphere (front half only)
    for lat in range(-60, 90, 30):
        pts = []
        for lo in range(0, 361, 10):
            a, b = math.radians(lat), math.radians(lo)
            pts.append((math.cos(a) * math.cos(b), math.cos(a) * math.sin(b), math.sin(a)))
        F.line(pts, 'gray!30, line width=0.3pt', depth=-10)
    for lo in range(0, 180, 30):
        pts = []
        for lat in range(-90, 91, 10):
            a, b = math.radians(lat), math.radians(lo)
            pts.append((math.cos(a) * math.cos(b), math.cos(a) * math.sin(b), math.sin(a)))
        F.line(pts, 'gray!30, line width=0.3pt', depth=-10)
    # a curve along which the plane rolls, and the transported vector by integrating the rolling rotor
    curve = []
    for s in range(0, 41):
        u = s / 40.0
        lat, lo = math.radians(10 + 50 * u), math.radians(-60 + 110 * u)
        curve.append((math.cos(lat) * math.cos(lo), math.cos(lat) * math.sin(lo), math.sin(lat)))
    F.line(curve, 'very thick, black!70', depth=5)
    v = unit(project_tangent((0.0, 0.3, 1.0), curve[0]))
    vs = [v]
    for k in range(1, len(curve)):
        v = rotor_between(curve[k - 1], curve[k])(v)   # rolling: the smallest rotation between consecutive normals
        vs.append(v)
    for k in (0, 13, 26, 40):
        x, n, vk = curve[k], curve[k], vs[k]
        F.poly(plane_patch(x, n, unit(vk), 0.22), 'draw=blue!50, fill=blue!12, fill opacity=0.75', depth=6 + k * 0.01)
